"""Generate crates/welkin-script-vm/src/builtins/constants_extra.rs.

LSL constants the compiler accepts (welkin-script-compiler BUILTIN_CONSTANTS) but
that the welkin-script-api CONSTANTS table has no value for, with values taken from
OpenSimulator's LSL_Constants.cs.

Usage: gen_lsl_constants.py <path to OpenSim LSL_Constants.cs> > constants_extra.rs
"""
import re
import sys

csharp = open(sys.argv[1]).read()
consts = {}
for m in re.finditer(r'public\s+const\s+(int|string|double|float|uint|long)\s+(\w+)\s*=\s*([^;]+);', csharp):
    consts[m.group(2)] = (m.group(1), m.group(3).strip())
vecs = {}
for m in re.finditer(r'public\s+static\s+readonly\s+(vector|rotation)\s+(\w+)\s*=\s*new\s+\w+\(([^)]*)\)\s*;', csharp):
    vecs[m.group(2)] = (m.group(1), [x.strip() for x in m.group(3).split(',')])

compiler = open('crates/welkin-script-compiler/src/builtins.rs').read()
names = re.findall(r'BuiltinConst \{ name: "(\w+)"', compiler)
api_src = open('crates/welkin-script-api/src/lib.rs').read()
api_src = api_src[api_src.index('pub static CONSTANTS'):api_src.index('pub static EVENTS')]
api_names = set(re.findall(r'name:\s*"(\w+)"', api_src))

def num(v):
    v = v.strip().rstrip('fF')
    return str(int(v, 16)) if v.lower().startswith(('0x', '-0x')) else v

out = ['// SPDX-License-Identifier: LGPL-3.0-or-later',
       '//! GENERATED by scripts/gen_lsl_constants.py from OpenSim LSL_Constants.cs. Do not edit.',
       '//! Constants the compiler accepts but the welkin-script-api table has no value for.',
       '',
       'pub enum Extra {',
       '    Int(i64),', '    Float(f64),', '    Str(&\'static str),',
       '    Vec3([f64; 3]),', '    Rot([f64; 4]),', '}', '',
       'pub static EXTRA_CONSTANTS: &[(&str, Extra)] = &[']
missing = []
for n in names:
    if n in api_names:
        continue
    if n in vecs:
        kind, parts = vecs[n]
        vals = ', '.join(f'{float(p)!r}' for p in parts)
        out.append(f'    ("{n}", Extra::{"Vec3" if kind == "vector" else "Rot"}([{vals}])),')
    elif n in consts:
        t, v = consts[n]
        if t == 'string':
            out.append(f'    ("{n}", Extra::Str({v})),')
        elif t in ('double', 'float') or '.' in v:
            out.append(f'    ("{n}", Extra::Float({float(num(v))!r})),')
        else:
            out.append(f'    ("{n}", Extra::Int({num(v)})),')
    else:
        missing.append(n)
out.append('];')
print('\n'.join(out))
if missing:
    sys.stderr.write('NOT FOUND in LSL_Constants.cs: ' + ', '.join(missing) + '\n')
    sys.exit(1)
